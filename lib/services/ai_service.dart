import 'package:supabase_flutter/supabase_flutter.dart';

class AIService {
  static Future<String> sendMessage(List<Map<String, dynamic>> messageHistory) async {
    try {
      if (messageHistory.isEmpty) return 'No prompt provided.';

      final lastMessage = messageHistory.last;
      final prompt = lastMessage['isUser'] ? lastMessage['text'] : '';

      // Pass previous history for conversational memory
      final history = messageHistory
          .sublist(0, messageHistory.length - 1)
          .map((m) => {'isUser': m['isUser'], 'text': m['text']})
          .toList();

      // Invokes your deployed Supabase Edge Function ('ai-tutor')
      final response = await Supabase.instance.client.functions.invoke(
        'ai-tutor',
        body: {
          'prompt': prompt,
          'history': history,
        },
      );

      if (response.status == 200 && response.data != null) {
        return response.data['reply'] ?? 'No response generated by Groq AI.';
      } else {
        return 'Server Error (${response.status}): ${response.data?['error'] ?? 'Unknown error'}';
      }
    } catch (e) {
      return 'Connection Error: Failed to reach Supabase Edge Function. (${e.toString()})';
    }
  }
}